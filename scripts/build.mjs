import { createHash } from 'node:crypto';
import { cp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const publicDir = resolve(root, 'public');
async function files(dir, prefix = '') {
  const entries = await readdir(dir, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) result.push(...await files(resolve(dir, entry.name), path + '/'));
    else if (path !== 'sw.js') result.push(path);
  }
  return result.sort();
}
const assets = await files(publicDir);
const hash = createHash('sha256');
for (const path of assets) { hash.update(path); hash.update(await readFile(resolve(publicDir, path))); }
const revision = hash.digest('hex').slice(0, 16);
const worker = `/* Generated by npm run build. Local assets only; API responses are never cached. */
const CACHE = 'auctionxi-local-${revision}';
const ASSETS = ${JSON.stringify(assets, null, 2)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('auctionxi-local-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || url.pathname === '/_realtime') return;
  const path = url.pathname.replace(/^\\//, '') || 'index.html';
  if (!ASSETS.includes(path) && event.request.mode !== 'navigate') return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    let timeout;
    try {
      const response = await Promise.race([
        fetch(event.request),
        new Promise((_, reject) => { timeout = setTimeout(() => reject(new Error('Network timeout')), 3000); }),
      ]);
      if (response.ok) await cache.put(event.request, response.clone());
      return response;
    } catch (error) {
      const cached = await cache.match(event.request);
      if (cached) return cached;
      if (event.request.mode === 'navigate') {
        const shell = await cache.match('index.html');
        if (shell) return shell;
      }
      throw error;
    } finally { clearTimeout(timeout); }
  })());
});
`;
await writeFile(resolve(publicDir, 'sw.js'), worker);
const out = resolve(root, 'dist'); await rm(out, { recursive: true, force: true });
await cp(publicDir, out, { recursive: true });
console.log(`Built ${assets.length + 1} local files; service-worker revision ${revision}.`);
